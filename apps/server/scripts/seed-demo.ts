/**
 * Creates a ready-to-explore demo account:
 *   - user demo@keyvane.local (password printed below)
 *   - project "Demo" with the AI PDF Analyzer product (Free / Pro / Business)
 *   - a secret + publishable API key and a Stripe webhook secret for the simulator
 *   - .env files for the example apps (never overwrites existing files)
 *
 * Usage: npm run seed:demo [-- --email you@example.com --password secret123 --sample-data]
 */
import { existsSync, writeFileSync } from 'node:fs';
import { createDemoCatalog } from '../src/dev/demo-catalog.ts';
import { randomBase62 } from '../src/lib/crypto.ts';
import { createApiKey, listApiKeys } from '../src/services/api-keys.ts';
import { createLicense } from '../src/services/licenses.ts';
import { createProject, setStripeWebhookSecret } from '../src/services/projects.ts';
import { upsertCustomer } from '../src/services/customers.ts';
import { recordUsage } from '../src/services/usage.ts';
import { createUser, getUserByEmail, setPassword } from '../src/services/users.ts';
import type { Actor } from '../src/types.ts';
import { openContext, parseArgs } from './_context.ts';

const { flags } = parseArgs(process.argv.slice(2));
const email = typeof flags.email === 'string' ? flags.email : 'demo@keyvane.local';
const password = typeof flags.password === 'string' ? flags.password : 'keyvane-demo';
const ctx = openContext();

let user = getUserByEmail(ctx, email);
if (user) {
  await setPassword(ctx, user.id, password);
} else {
  user = await createUser(ctx, { email, password, name: 'Demo Developer' });
}
const actor: Actor = { type: 'user', id: user.id, label: user.email };

const project = createProject(ctx, user.id, { name: `Demo (${new Date().toISOString().slice(0, 10)})` }, actor);
const catalog = createDemoCatalog(ctx, project.id, actor);
const secret = createApiKey(ctx, project.id, { type: 'secret', name: 'Demo server' }, actor).token;
const publishable = listApiKeys(ctx, project.id).find((k) => k.type === 'publishable')?.token_plain ?? '';
const webhookSecret = `whsec_demo${randomBase62(24)}`;
setStripeWebhookSecret(ctx, project.id, webhookSecret, actor);

let sampleLicense: string | null = null;
if (flags['sample-data']) {
  const system: Actor = { type: 'system', label: 'seed' };
  for (const [id, mail, name] of [
    ['user_ada', 'ada@example.com', 'Ada Lovelace'],
    ['user_grace', 'grace@example.com', 'Grace Hopper'],
    ['user_linus', 'linus@example.com', 'Linus'],
  ] as const) {
    upsertCustomer(ctx, project.id, { externalId: id, email: mail, name }, system);
  }
  createLicense(ctx, project.id, { plan: 'business', customer: 'user_grace', note: 'Design partner' }, 'dashboard', actor);
  for (let i = 0; i < 7; i++) recordUsage(ctx, project.id, { customer: 'user_ada', feature: 'pdf_analysis' }, system);
  for (let i = 0; i < 42; i++) recordUsage(ctx, project.id, { customer: 'user_grace', feature: 'pdf_analysis' }, system);
  sampleLicense = createLicense(ctx, project.id, { plan: 'pro', durationDays: 365, note: 'Desktop CLI demo' }, 'dashboard', actor).key;
}

const url = ctx.config.publicUrl;
const envFiles: [string, string][] = [
  [
    new URL('../../../examples/pdf-analyzer/.env', import.meta.url).pathname,
    `# Generated by npm run seed:demo\nKEYVANE_URL=${url}\nKEYVANE_SECRET_KEY=${secret}\nKEYVANE_PRODUCT=${catalog.product.key}\nPORT=3000\n# Optional: a Stripe Payment Link for the Pro plan (test mode)\n# STRIPE_PAYMENT_LINK_PRO=https://buy.stripe.com/test_...\n`,
  ],
  [
    new URL('../../../examples/license-cli/.env', import.meta.url).pathname,
    `# Generated by npm run seed:demo\nKEYVANE_URL=${url}\nKEYVANE_PUBLISHABLE_KEY=${publishable}\nKEYVANE_PRODUCT=${catalog.product.key}\n`,
  ],
];
const written: string[] = [];
for (const [path, content] of envFiles) {
  if (existsSync(path) || !existsSync(new URL('.', `file://${path}`))) continue;
  writeFileSync(path, content);
  written.push(path);
}

console.log(`
Keyvane demo ready
────────────────────
Dashboard        ${url}/login
Email            ${email}
Password         ${password}

Project          ${project.name} (${project.id})
Product          ${catalog.product.name} — plans: free, pro, business
Secret key       ${secret}
Publishable key  ${publishable}
Webhook secret   ${webhookSecret}  (used by npm run stripe:simulate)
${sampleLicense ? `Sample license   ${sampleLicense}\n` : ''}
${written.length ? `Wrote ${written.join('\n      ')}\n` : 'Example .env files already exist — not overwritten.\n'}
Next steps
  1. npm run dev                      # start Keyvane on ${url}
  2. npm run dev --workspace pdf-analyzer-example   # the sample app on http://localhost:3000
  3. npm run stripe:simulate -- subscribe --project ${project.id} --customer user_alex --plan pro
`);
ctx.db.close();
